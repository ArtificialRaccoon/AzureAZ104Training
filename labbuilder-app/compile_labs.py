#!/usr/bin/env python3
"""
labbuilder-app/compile_labs.py
Validates, checks for duplicates, and compiles all modular lab files
(labs/path-01.json through labs/path-06.json) into:
  - labbuilder-app/labs.json
  - labbuilder-app/labs.js (window.LAB_DATA = [...])
"""

import json
import os
import sys

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
LABS_DIR = os.path.join(BASE_DIR, "labs")
OUTPUT_JSON = os.path.join(BASE_DIR, "labs.json")
OUTPUT_JS = os.path.join(BASE_DIR, "labs.js")

PATH_FILES = [
    "path-01.json",
    "path-02.json",
    "path-03.json",
    "path-04.json",
    "path-05.json",
    "path-06.json"
]

REQUIRED_LAB_FIELDS = [
    "id",
    "section",
    "pathName",
    "topic",
    "title",
    "difficulty",
    "estimatedMinutes",
    "summary",
    "scenarioTemplate",
    "variables",
    "acceptanceCriteria",
    "steps"
]

REQUIRED_STEP_FIELDS = [
    "stepNumber",
    "title",
    "portalGuide",
    "cliCommand",
    "powershellCommand",
    "validation"
]

def main():
    all_labs = []
    seen_ids = set()
    stats_by_path = {}

    print("==================================================")
    print("AZ-104 LabBuilder Archetype Compiler & Validator")
    print("==================================================")

    for path_filename in PATH_FILES:
        filepath = os.path.join(LABS_DIR, path_filename)
        if not os.path.exists(filepath):
            print(f"ERROR: Lab file not found: {filepath}", file=sys.stderr)
            sys.exit(1)

        with open(filepath, "r", encoding="utf-8") as f:
            try:
                labs = json.load(f)
            except Exception as e:
                print(f"ERROR parsing {path_filename}: {e}", file=sys.stderr)
                sys.exit(1)

        stats_by_path[path_filename] = len(labs)
        print(f"Loaded {path_filename}: {len(labs)} lab archetypes")

        for idx, lab in enumerate(labs):
            lab_id = lab.get("id")
            if not lab_id:
                print(f"ERROR in {path_filename}[{idx}]: Missing 'id'", file=sys.stderr)
                sys.exit(1)

            if lab_id in seen_ids:
                print(f"ERROR: Duplicate lab ID '{lab_id}' in {path_filename}[{idx}]", file=sys.stderr)
                sys.exit(1)
            seen_ids.add(lab_id)

            for req in REQUIRED_LAB_FIELDS:
                if req not in lab:
                    print(f"ERROR in {lab_id}: Missing required field '{req}'", file=sys.stderr)
                    sys.exit(1)

            steps = lab.get("steps", [])
            if not isinstance(steps, list) or len(steps) == 0:
                print(f"ERROR in {lab_id}: 'steps' must be a non-empty list", file=sys.stderr)
                sys.exit(1)

            for step_idx, step in enumerate(steps):
                for step_req in REQUIRED_STEP_FIELDS:
                    if step_req not in step:
                        print(f"ERROR in {lab_id} step {step_idx + 1}: Missing '{step_req}'", file=sys.stderr)
                        sys.exit(1)

            all_labs.append(lab)

    print("\n--------------------------------------------------")
    print("Writing Compiled Datasets...")
    print("--------------------------------------------------")

    # 1. Write pure JSON
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(all_labs, f, indent=2, ensure_ascii=False)
    print(f"-> Wrote {OUTPUT_JSON} ({len(all_labs)} labs)")

    # 2. Write window.LAB_DATA JS
    js_content = (
        "/**\n"
        " * labbuilder-app/labs.js\n"
        " * Auto-generated by compile_labs.py. Do not edit manually.\n"
        f" * Total Labs: {len(all_labs)}\n"
        " */\n\n"
        f"window.LAB_DATA = {json.dumps(all_labs, indent=2, ensure_ascii=False)};\n"
    )
    with open(OUTPUT_JS, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"-> Wrote {OUTPUT_JS} ({len(all_labs)} labs)")

    print("\n==================================================")
    print(f"SUCCESS: Compiled {len(all_labs)} total labs across {len(PATH_FILES)} paths!")
    for path_file, count in stats_by_path.items():
        print(f"  - {path_file}: {count} labs")
    print("==================================================")

if __name__ == "__main__":
    main()
